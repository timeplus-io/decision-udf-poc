#!/usr/bin/env python3
"""
build_sql.py — wrap decide_udf.py into CREATE FUNCTION statements for Timeplus / Proton.

    python udf/build_sql.py --backend local --base-url http://decision:8080 --model decider-2b-q8_0 > sql/02_udf.sql
    python udf/build_sql.py --backend jev   --model jev-1.13.0                                  > sql/02_udf.sql
    python udf/build_sql.py --backend mock                                                       > sql/02_udf.sql

Emits three functions (decide_noul, decide_choice, decide_score), each carrying the full module body, separated
by a line containing only "-- ;;" so callers can split statements safely.
--no-init-hook  omits SETTINGS init_function_name/init_function_parameters for engines without init-hook support
                (the module then lazily initialises from defaults + DECISION_* env vars).
"""
import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FUNCS = [
    ("decide_noul", "state string, question string"),
    ("decide_choice", "state string, question string, options string"),
    ("decide_score", "state string, question string, levels string"),
]
SEP = "-- ;;"


def build(args):
    with open(os.path.join(HERE, "decide_udf.py"), encoding="utf-8") as f:
        body = f.read().rstrip()
    if "$$" in body:
        sys.exit("decide_udf.py must not contain '$$'")
    params = {
        "backend": args.backend, "base_url": args.base_url, "model": args.model,
        "pack_rows": args.pack_rows, "max_in_flight": args.max_in_flight, "timeout_s": args.timeout_s,
        "block_deadline_s": args.block_deadline_s, "cache_ttl_s": args.cache_ttl_s,
        "temperatures": json.load(open(args.temperatures)) if args.temperatures else {},
    }
    params_json = json.dumps(params, separators=(",", ":")).replace("'", "''")
    settings = "" if args.no_init_hook else (
        "\nSETTINGS init_function_name = '_tp_init',\n         init_function_parameters = '%s'" % params_json)
    out = ["-- generated by udf/build_sql.py; backend=%s model=%s" % (args.backend, args.model or "(any)")]
    for name, sig in FUNCS:
        out.append("CREATE OR REPLACE FUNCTION %s(%s)\nRETURNS string LANGUAGE PYTHON AS $$\n%s\n$$%s;\n%s"
                   % (name, sig, body, settings, SEP))
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--backend", default="mock", choices=["jev", "local", "mock"])
    ap.add_argument("--base-url", default="http://decision:8080")
    ap.add_argument("--model", default="")
    ap.add_argument("--pack-rows", type=int, default=16)
    ap.add_argument("--max-in-flight", type=int, default=6)
    ap.add_argument("--timeout-s", type=float, default=5.0)
    ap.add_argument("--block-deadline-s", type=float, default=20.0)
    ap.add_argument("--cache-ttl-s", type=float, default=0)
    ap.add_argument("--temperatures", default="", help="path to JSON {question: T}")
    ap.add_argument("--no-init-hook", action="store_true")
    sys.stdout.write(build(ap.parse_args()))


if __name__ == "__main__":
    main()
